import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Run on every build, including automatic incubation/maturity publications.
// Originals and the artwork registry are never rewritten.
export async function buildArtworkPreviews(root, output, artwork) {
  const directory = path.join(output, "assets/artwork/previews");
  await mkdir(directory, { recursive: true });
  const previews = {};
  for (const src of new Set(Object.values(artwork).map(art => art.src))) {
    if (!/^\/assets\/artwork\/[a-z0-9-]+\.webp$/.test(src))
      throw new Error(`Unsupported cover path: ${src}`);
    const input = await readFile(path.join(root, src));
    const { width, height, pages = 1, orientation = 1 } = await sharp(input).metadata();
    if (!width || !height || pages !== 1 || orientation !== 1)
      throw new Error(`Cover must be a still, upright image: ${src}`);
    // Include bytes and encoding version so a replaced image cannot reuse stale previews.
    const hash = createHash("sha256").update(input).update("preview-v1-q82").digest("hex").slice(0, 16);
    const candidates = [];
    for (const size of [160, 320, 640].filter(size => size < width)) {
      const name = `${path.basename(src, ".webp")}-${hash}-${size}.webp`;
      await sharp(input).resize({ width: size, withoutEnlargement: true })
        .webp({ quality: 82, effort: 5 }).toFile(path.join(directory, name));
      candidates.push(`/assets/artwork/previews/${name} ${size}w`);
    }
    candidates.push(`${src} ${width}w`);
    previews[src] = { width, height, srcset: candidates.join(", ") };
  }
  await writeFile(path.join(output, "assets/artwork-previews.js"),
    `// Generated by the public build; original artwork stays unchanged.\nexport default ${JSON.stringify(previews)};\n`);
  // sizes=auto needs an explicit aspect ratio: intrinsic size containment can
  // otherwise give width:auto a 300px fallback. Keep these rules external for CSP.
  const ratios = new Set(Object.values(previews).map(({ width, height }) =>
    `#tracks[data-view="grid"] .track-art-frame .track-art[width="${width}"][height="${height}"] { aspect-ratio: ${width} / ${height}; }`));
  await writeFile(path.join(output, "assets/artwork-previews.css"),
    `/* Generated native cover proportions. */\n@media (max-width: 540px) {\n${[...ratios].join("\n")}\n}\n`);
  console.log(`Prepared responsive previews for ${Object.keys(previews).length} covers.`);
  return previews;
}
